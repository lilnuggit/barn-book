// Renders the app icon to the PNG sizes iOS and the web manifest need.
// Run with: node scripts/make-icons.mjs
import sharp from "sharp";
import { writeFile } from "node:fs/promises";

const SHOE =
  "M5.2 21C2.6 16.5 2.7 9.6 6.3 6C8 4.3 9.9 3.4 12 3.4C14.1 3.4 16 4.3 17.7 6C21.3 9.6 21.4 16.5 18.8 21" +
  "L15.3 20.2C17.3 16.4 17.4 11.4 15.2 9C14.3 8 13.2 7.5 12 7.5C10.8 7.5 9.7 8 8.8 9C6.6 11.4 6.7 16.4 8.7 20.2Z";
const HOLES = [
  [6.25, 9.55], [5.3, 13.4], [5.65, 17.2],
  [17.75, 9.55], [18.7, 13.4], [18.35, 17.2],
];

function iconSvg({ size, scale, bg = "#2E5546", fg = "#F3EBDA", rounded = false }) {
  const holes = HOLES.map(([x, y]) => `<circle cx="${x}" cy="${y}" r="0.62" fill="${bg}"/>`).join("");
  const r = rounded ? size * 0.225 : 0;
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 ${size} ${size}">
  <defs><linearGradient id="g" x1="0" y1="0" x2="0" y2="1">
    <stop offset="0" stop-color="#376452"/><stop offset="1" stop-color="${bg}"/></linearGradient></defs>
  <rect width="${size}" height="${size}" rx="${r}" fill="url(#g)"/>
  <g transform="translate(${size / 2} ${size * 0.53}) scale(${(size / 24) * scale}) translate(-12 -12.1)">
    <path d="${SHOE}" fill="${fg}"/>${holes}
  </g>
</svg>`;
}

const out = "public";
const jobs = [
  ["apple-icon.png", 180, 0.74, "src/app"],
  ["icon-192.png", 192, 0.74, out],
  ["icon-512.png", 512, 0.74, out],
  ["icon-maskable-512.png", 512, 0.56, out],
];
for (const [name, size, scale, dir] of jobs) {
  await sharp(Buffer.from(iconSvg({ size, scale }))).png().toFile(`${dir}/${name}`);
}
await writeFile("src/app/icon.svg", iconSvg({ size: 64, scale: 0.78, rounded: true }));
await writeFile("src/components/horseshoe-path.ts",
  `// Generated by scripts/make-icons.mjs\nexport const SHOE_PATH = ${JSON.stringify(SHOE)};\nexport const SHOE_HOLES = ${JSON.stringify(HOLES)} as const;\n`);
console.log("icons written");
